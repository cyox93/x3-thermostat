// Renders the design's SVG icons with headless Chrome and writes LVGL 9 C arrays.
// usage: node build-icons.mjs [outDir]   (default ../../components/ui/icons)
// Colour icons → ARGB8888; mono flames → A8 (recoloured at runtime).
import puppeteer from 'puppeteer';
import fs from 'node:fs';
import path from 'node:path';
import { PNG } from 'pngjs';

const outDir = process.argv[2] || '../../components/ui/icons';
fs.mkdirSync(outDir, { recursive: true });

// Paths from design/src/boiler-app.jsx FlameIcon / StatusBar
const FLAME_OUTER = 'M8 0.5C8.6 4 12.5 6.2 13.6 10.2C14.8 14.6 11.9 19.5 8 19.5C4.1 19.5 1.2 16.4 1.9 12.3C2.3 10 3.6 8.6 4.6 7.4C4.8 9.4 5.6 10.6 6.6 11C6.2 7.2 7.6 3.6 8 0.5Z';
const FLAME_INNER = 'M8.2 10.2C9.9 12 11 13.6 10.6 15.7C10.2 17.6 9.1 18.4 8 18.4C6.6 18.4 5.4 17.3 5.6 15.6C5.8 14.2 6.9 13.4 7.4 12.3C7.8 13.1 8.3 13.5 8.7 13.6C8.7 12.4 8.4 11.3 8.2 10.2Z';
// The design draws flames at size × 1.25 (14 → 17.5); heights are rounded up to whole pixels.
const flame = (w, h, mono) => `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 16 20" preserveAspectRatio="none" style="display:block">` +
  `<path d="${FLAME_OUTER}" fill="${mono ? '#ffffff' : '#e88a5e'}"/>` +
  (mono ? '' : `<path d="${FLAME_INNER}" fill="#ffd27a"/>`) + `</svg>`;
const wifi = (level) => {
  const arcs = [3, 2, 1].map((_, i) => {
    const r = 3 + i * 2, active = level >= 3 - i;
    return `<path d="M ${6.5 - r} 10 A ${r} ${r} 0 0 1 ${6.5 + r} 10" fill="none" stroke="${active ? '#ffffff' : '#d0d0d4'}" stroke-width="1.2" opacity="${active ? 0.9 : 0.3}"/>`;
  }).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="14" height="12" viewBox="0 0 13 11" style="display:block">${arcs}<circle cx="6.5" cy="10" r="0.9" fill="#ffffff"/></svg>`;
};

const ICONS = [
  { name: 'img_flame_color_14', w: 14, h: 18, svg: flame(14, 18), cf: 'ARGB8888' },
  { name: 'img_flame_color_10', w: 10, h: 13, svg: flame(10, 13), cf: 'ARGB8888' },
  { name: 'img_flame_mono_9',   w: 9,  h: 11, svg: flame(9, 11, true),  cf: 'A8' },
  ...[0, 1, 2, 3].map(l => ({ name: `img_wifi_${l}`, w: 14, h: 12, svg: wifi(l), cf: 'ARGB8888' })),
];

const browser = await puppeteer.launch({ args: ['--force-color-profile=srgb'] });
const page = await browser.newPage();
await page.setViewport({ width: 32, height: 32, deviceScaleFactor: 1 });

for (const ic of ICONS) {
  await page.setContent(`<html><body style="margin:0;background:transparent">${ic.svg}</body></html>`);
  const buf = await page.screenshot({ clip: { x: 0, y: 0, width: ic.w, height: ic.h }, omitBackground: true });
  const png = PNG.sync.read(Buffer.from(buf));
  const bytes = [];
  for (let i = 0; i < ic.w * ic.h; i++) {
    const [r, g, b, a] = png.data.subarray(i * 4, i * 4 + 4);
    if (ic.cf === 'A8') bytes.push(a);
    else bytes.push(b, g, r, a);              // LVGL ARGB8888 is B,G,R,A in memory
  }
  const stride = ic.cf === 'A8' ? ic.w : ic.w * 4;
  const rows = [];
  for (let y = 0; y < ic.h; y++) rows.push('    ' + bytes.slice(y * stride, (y + 1) * stride).map(v => '0x' + v.toString(16).padStart(2, '0')).join(','));
  const c = `/* Generated by design/tools/build-icons.mjs — do not edit */
#ifdef LV_LVGL_H_INCLUDE_SIMPLE
#include "lvgl.h"
#else
#include "lvgl/lvgl.h"
#endif

static const uint8_t ${ic.name}_map[] = {
${rows.join(',\n')}
};

const lv_image_dsc_t ${ic.name} = {
    .header = {
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_${ic.cf},
        .w = ${ic.w},
        .h = ${ic.h},
        .stride = ${stride},
    },
    .data_size = sizeof(${ic.name}_map),
    .data = ${ic.name}_map,
};
`;
  fs.writeFileSync(path.join(outDir, `${ic.name}.c`), c);
  console.log('✓', ic.name);
}
await browser.close();
